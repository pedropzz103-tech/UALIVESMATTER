function routeRiskScore(route){
  const coords=route?.geometry?.coordinates||[];
  if(!coords.length)return 999999;
  let score=0;
  const step=Math.max(1,Math.floor(coords.length/160));
  for(let i=0;i<coords.length;i+=step){
    const lng=coords[i][0],lat=coords[i][1];
    for(const area of riskAreas){
      if(area.kind==='circle'){
        const d=distanceKm(lat,lng,area.lat,area.lng)*1000;
        if(d<=area.radius)score+=area.severity*area.severity*4;
      }else if(area.kind==='bounds'&&area.bounds?.contains([lat,lng])){
        score+=area.severity*area.severity*3;
      }
    }
    for(const seg of frontlineSegments){
      const d=pointSegmentKm(lat,lng,seg[0],seg[1]);
      if(d<=15)score+=80;
      else if(d<=30)score+=35;
      else if(d<=50)score+=10;
    }
  }
  return score;
}
