function pointSegmentKm(lat,lon,a,b){
  const refLat=(lat+(a[1]||lat)+(b[1]||lat))/3*Math.PI/180;
  const kx=111.32*Math.cos(refLat),ky=110.57;
  const ax=(a[0]-lon)*kx,ay=(a[1]-lat)*ky;
  const bx=(b[0]-lon)*kx,by=(b[1]-lat)*ky;
  const vx=bx-ax,vy=by-ay;
  const len=vx*vx+vy*vy;
  let q=0;
  if(len>0)q=Math.max(0,Math.min(1,-(ax*vx+ay*vy)/len));
  const x=ax+q*vx,y=ay+q*vy;
  return Math.sqrt(x*x+y*y);
}
async function refreshRiskZones(){
  safetyLayers.risk.clearLayers();
  riskAreas=riskAreas.filter(x=>x.source==='air');
  const now=Date.now();

  try{
    if(sb){
      const since=new Date(now-12*3600e3).toISOString();
      const {data}=await sb.from('community_alerts')
        .select('id,type,text,lat,lng,confirmations,rejections,created_at')
        .gte('created_at',since)
        .order('created_at',{ascending:false})
        .limit(350);
      (data||[]).forEach(a=>{
        if(!Number.isFinite(Number(a.lat))||!Number.isFinite(Number(a.lng)))return;
        let severity=1;
        if(['danger','fire','medical'].includes(a.type))severity=3;
        else if(['road','shelter','power','heating','water'].includes(a.type))severity=2;
        if((a.confirmations||0)>=3)severity=Math.min(3,severity+1);
        if((a.rejections||0)>(a.confirmations||0))severity=1;
        const radius=Math.min(4500,700+Math.max(0,a.confirmations||0)*350+(severity*350));
        const color=riskColor(severity);
        L.circle([a.lat,a.lng],{
          radius,color,weight:1.3,fillColor:color,fillOpacity:severity===3?.22:severity===2?.17:.12,
          interactive:true
        }).addTo(safetyLayers.risk)
          .bindPopup('<b>'+esc(typeLabel(a.type))+'</b><br>'+esc(a.text||'')+'<br><small>'+esc(t('riskZones'))+'</small>');
        riskAreas.push({kind:'circle',lat:Number(a.lat),lng:Number(a.lng),radius,severity,source:'community'});
      });

      const {data:zones}=await sb.from('civil_risk_zones')
        .select('*')
        .eq('active',true)
        .limit(100);
      (zones||[]).forEach(z=>{
        try{
          const color=riskColor(z.severity);
          const gj=L.geoJSON(z.geojson,{style:{color,weight:1.5,fillColor:color,fillOpacity:z.severity>=3?.26:z.severity===2?.18:.12}})
            .addTo(safetyLayers.risk)
            .bindPopup('<b>'+esc(langField(z,'name'))+'</b><br><small>'+esc(z.source_name||'')+'</small>');
          gj.eachLayer(x=>{if(x.getBounds)riskAreas.push({kind:'bounds',bounds:x.getBounds(),severity:Number(z.severity),source:'curated'})});
        }catch(e){}
      });
    }
  }catch(e){console.warn('risk zones unavailable',e)}
  await loadFrontlineRisk();
}
