function ensureSafetyLayer(name,on=true){
  const layer=safetyLayers[name];
  if(!layer)return;
  if(on&&!map.hasLayer(layer))map.addLayer(layer);
  const btn=document.getElementById(name==='air'?'btnAir':'btnRisk');
  if(btn)btn.classList.toggle('on',map.hasLayer(layer));
}
async function openSafetyFeature(kind){
  const nav=document.querySelector('.nav button[onclick*="page(\'map\'"]');
  if(kind==='utilities'){
    if(nav)page('map',nav);
    if(!map.hasLayer(layers.utilities))map.addLayer(layers.utilities);
    document.getElementById('btnUtilities')?.classList.add('on');
    return;
  }
  if(kind==='transport'){
    if(nav)page('map',nav);
    if(!map.hasLayer(layers.transport))map.addLayer(layers.transport);
    document.getElementById('btnTransport')?.classList.add('on');
    refreshDynamicLayers(true);
    return;
  }
  if(kind==='kit'){
    const safetyNav=document.querySelector('.nav button[onclick*="page(\'survival\'"]');
    if(safetyNav)page('survival',safetyNav);
    return;
  }
  if(nav)page('map',nav);
  if(kind==='air'){ensureSafetyLayer('air',true);await loadAirAlertZones(true);map.setView([49.0,31.2],6)}
  if(kind==='risk'){ensureSafetyLayer('risk',true);await refreshRiskZones()}
  if(kind==='shelter'){if(!map.hasLayer(layers.shelter))map.addLayer(layers.shelter);document.getElementById('btnShelter')?.classList.add('on');locateMe()}
  if(kind==='route')routeToNearestShelter();
}
window.openSafetyFeature=openSafetyFeature;

async function openResourcesSheet(){
  const sheet=document.getElementById('resourcesSheet');
  sheet.classList.add('open');
  const box=document.getElementById('verifiedResources');
  if(resourcesLoaded)return;
  box.innerHTML='<div class="resource-loading">…</div>';
  try{
    const {data,error}=await sb.from('verified_resources').select('*').eq('verified',true).order('sort_order');
    if(error)throw error;
    box.innerHTML=(data||[]).map(x=>{
      const desc=x['description_'+currentLang]||x.description_uk||x.description_en||'';
      return '<button class="resource-card" onclick="openExternal(\''+esc(x.url)+'\')">'+
        '<span class="resource-mark">'+(x.kind==='charity'?'♥':'✓')+'</span>'+
        '<span class="resource-copy"><b>'+esc(x.name)+'</b><small>'+esc(desc)+'</small></span><i>↗</i>'+
      '</button>';
    }).join('')||'<div class="empty-state">'+t('noResources')+'</div>';
    resourcesLoaded=true;
  }catch(e){box.innerHTML='<div class="empty-state">'+t('noResources')+'</div>'}
}
function closeResourcesSheet(){document.getElementById('resourcesSheet').classList.remove('open')}
